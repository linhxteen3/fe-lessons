    await page.locator('#unit-convention').selectOption('1024');
    assert.match(await page.locator('#unit-result').textContent(), /1 MiB = 1,048,576 byte/);
    await page.locator('#unit-level').fill('0');
    assert.equal(await page.locator('#unit-result').textContent(), '1 bit = 0.125 byte');
    await page.locator('.unit-ladder button').nth(4).click();
    assert.equal(await page.locator('#unit-level').inputValue(), '4');
    assert.match(await page.locator('#unit-result').textContent(), /1 GiB/);
    await page.setViewportSize({width:831,height:668});
    await page.locator('#unit-level').scrollIntoViewIfNeeded();
    const slider = await page.locator('#unit-level').boundingBox();
    await page.mouse.move(slider.x + slider.width - 8, slider.y + slider.height / 2);
    await page.mouse.down();
    await page.mouse.move(slider.x + 8, slider.y + slider.height / 2, {steps:12});
    await page.mouse.up();
    assert.equal(await page.locator('#unit-level').inputValue(), '0');
    await page.locator('#unit-level').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#unit-level').inputValue(), '1');
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#character-choice').selectOption('あ');
