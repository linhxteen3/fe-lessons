    await page.waitForFunction(() => Number(document.querySelectorAll('.byte-result strong')[1].textContent) >= 2);
    await page.locator('#byte-demo').click();
    assert.equal(await page.locator('#byte-demo').getAttribute('aria-pressed'), 'false');
    const stoppedValue = await page.locator('.byte-result strong').nth(1).textContent();
    await page.waitForTimeout(750);
    assert.equal(await page.locator('.byte-result strong').nth(1).textContent(), stoppedValue);
    await page.locator('#byte-demo').click();
    await page.locator('.classroom-next').click();
    assert.equal(await page.locator('#byte-demo').getAttribute('aria-pressed'), 'false');
    assert.ok(await page.locator('#p1').isVisible());
    const toolbarBox = await page.locator('.classroom-toolbar').boundingBox();
    const topicBox = await page.locator('#topic-4').boundingBox();
    assert.ok(toolbarBox.x >= topicBox.x + topicBox.width, 'Steps are on the right');
